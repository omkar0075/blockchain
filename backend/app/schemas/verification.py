from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional
from uuid import UUID, uuid4
from pydantic import BaseModel, Field, field_validator, model_validator, ConfigDict

from .resource_request import FORBIDDEN_PII_KEYWORDS


class VerificationStatus(str, Enum):
    """
    Overall safety and eligibility status of a provider offer.
    
    Critical Architectural Rule:
    A verification result is strictly a point-in-time SNAPSHOT, NOT a permanent guarantee.
    Capacity, quotas, and institutional authorization must be atomically rechecked
    at the time of the smart contract two-phase commit lock or reservation transaction.
    """
    PENDING = "PENDING"
    VERIFIED = "VERIFIED"
    REJECTED = "REJECTED"
    REQUIRES_REVIEW = "REQUIRES_REVIEW"


class VerificationChecklist(BaseModel):
    """
    Structured checklist representing individual verification dimensions.
    """
    model_config = ConfigDict(extra="ignore")

    institution_registered: bool = Field(
        default=False,
        description="Whether provider institution is registered in registry",
    )
    institution_active: bool = Field(
        default=False,
        description="Whether provider institution is in active standing",
    )
    wallet_authorized: bool = Field(
        default=False,
        description="Whether provider wallet is authorized and matches registry",
    )
    resource_registered: bool = Field(
        default=False,
        description="Whether resource type is registered under provider on-chain",
    )
    offer_unexpired: bool = Field(
        default=False,
        description="Whether offer validity window has not elapsed",
    )
    capacity_available: bool = Field(
        default=False,
        description="Whether real-time on-chain uncommitted capacity meets requested quantity",
    )
    request_compatible: bool = Field(
        default=False,
        description="Whether offer meets requester specifications, urgency, and constraints",
    )

    def is_all_passed(self) -> bool:
        """Returns True if every required verification check passed."""
        return all([
            self.institution_registered,
            self.institution_active,
            self.wallet_authorized,
            self.resource_registered,
            self.offer_unexpired,
            self.capacity_available,
            self.request_compatible,
        ])


class FailedCheck(BaseModel):
    """Machine-readable detail of a specific failed verification check."""
    model_config = ConfigDict(extra="ignore")

    check_name: str = Field(..., min_length=1, description="Name of the failed check")
    reason_code: str = Field(..., min_length=1, description="Machine-readable error code")
    message: str = Field(..., min_length=1, description="Operational explanation")

    @field_validator("check_name", "reason_code", "message")
    @classmethod
    def clean_text(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Field cannot be empty or whitespace only")
        return stripped


class VerificationResult(BaseModel):
    """
    Snapshot verification outcome generated by Verification Agent.
    
    Contains point-in-time validation results across institutional,
    cryptographic, capacity, and compatibility dimensions.
    """
    model_config = ConfigDict(extra="ignore")

    # Identifiers
    verification_id: UUID = Field(
        default_factory=uuid4,
        description="Unique verification snapshot identifier",
    )
    workflow_id: UUID = Field(
        ...,
        description="Parent multi-agent workflow tracking this coordination process",
    )
    provider_id: str = Field(
        ...,
        min_length=1,
        description="Identifier of provider institution being verified",
    )
    offer_id: UUID = Field(
        ...,
        description="ProviderOffer being verified",
    )
    request_id: Optional[UUID] = Field(
        default=None,
        description="Associated ResourceRequest ID",
    )

    # Status & Checklist
    status: VerificationStatus = Field(
        ...,
        description="Overall status: PENDING, VERIFIED, REJECTED, REQUIRES_REVIEW",
    )
    checks: VerificationChecklist = Field(
        default_factory=VerificationChecklist,
        description="Individual status for each verification dimension",
    )
    failed_checks: list[FailedCheck] = Field(
        default_factory=list,
        description="List of failed checks with machine-readable reason codes",
    )

    # Timestamp & Operational explanation
    verified_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Point-in-time timestamp when verification checks ran (UTC, timezone-aware)",
    )
    explanation: Optional[str] = Field(
        default=None,
        description="Operational log summary strictly without patient PII",
    )
    onchain_block_number: Optional[int] = Field(
        default=None,
        ge=0,
        description="Coral Testnet block number at time of on-chain verification snapshot",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Operational coordination metadata",
    )

    @field_validator("provider_id")
    @classmethod
    def validate_provider_id(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("provider_id cannot be empty or whitespace only")
        return stripped

    @field_validator("verified_at")
    @classmethod
    def validate_timezone(cls, v: datetime) -> datetime:
        if v.tzinfo is None or v.tzinfo.utcoffset(v) is None:
            raise ValueError("verified_at timestamp must be timezone-aware (UTC)")
        return v

    @model_validator(mode="before")
    @classmethod
    def reject_pii(cls, values: Any) -> Any:
        """Enforces design principle: reject any attempt to include patient PII."""
        if isinstance(values, dict):
            keys = set(values.keys())
            found_pii = keys.intersection(FORBIDDEN_PII_KEYWORDS)
            if found_pii:
                raise ValueError(
                    f"Privacy violation: patient identifying fields are strictly forbidden in verification ({', '.join(sorted(found_pii))})"
                )
        return values

    @model_validator(mode="after")
    def validate_status_consistency(self) -> "VerificationResult":
        """Ensures logical consistency between status, checks, and failed_checks."""
        if self.status == VerificationStatus.VERIFIED:
            if not self.checks.is_all_passed():
                raise ValueError("status cannot be VERIFIED when one or more individual checks failed")
            if self.failed_checks:
                raise ValueError("status cannot be VERIFIED when failed_checks list is non-empty")
        elif self.status == VerificationStatus.REJECTED:
            if self.checks.is_all_passed() and not self.failed_checks:
                raise ValueError("status cannot be REJECTED when all checks passed and no failed_checks are recorded")
        return self
